    ///
    /// List the dubs you have access to.
    ///
    /// # Arguments
    ///
    /// * `request` - Query parameters for this request
    /// * `options` - Per-call overrides
    ///
    /// # Returns
    ///
    /// Successful Response
    #[deprecated]
    pub async fn list(
        &self,
        request: &DubbingListQueryRequest,
        options: Option<RequestOptions>,
    ) -> Result<DubbingMetadataPageResponseModel, crate::error::ApiError> {
        let cursor = request.cursor.clone();
        let page_size = request.page_size.clone();
        let dubbing_status = request.dubbing_status.clone();
        let dubbing_statuses = request.dubbing_statuses.clone();
        let dubbing_models = request.dubbing_models.clone();
        let target_language_codes = request.target_language_codes.clone();
        let creation_sources = request.creation_sources.clone();
        let filter_by_creator = request.filter_by_creator.clone();
        let order_by = request.order_by.clone();
        let order_direction = request.order_direction.clone();
        let url = "/v1/dubbing";

        let mut request = self.http_client.get(url);
        if let Some(val) = &cursor {
            request = request.query(&[("cursor", &val.to_string())]);
        }
        if let Some(val) = &page_size {
            request = request.query(&[("page_size", &val.to_string())]);
        }
        if let Some(val) = &dubbing_status {
            request = request.query(&[("dubbing_status", &val.to_string())]);
        }
        if let Some(val) = &dubbing_statuses {
            for item in val.iter() {
                request = request.query(&[("dubbing_statuses", &item.to_string())]);
            }
        }
        if let Some(val) = &dubbing_models {
            for item in val.iter() {
                request = request.query(&[("dubbing_models", &item.to_string())]);
            }
        }
        if let Some(val) = &target_language_codes {
            for item in val.iter() {
                request = request.query(&[("target_language_codes", &item.to_string())]);
            }
        }
        if let Some(val) = &creation_sources {
            for item in val.iter() {
                request = request.query(&[("creation_sources", &item.to_string())]);
            }
        }
        if let Some(val) = &filter_by_creator {
            request = request.query(&[("filter_by_creator", &val.to_string())]);
        }
        if let Some(val) = &order_by {
            request = request.query(&[("order_by", &val.to_string())]);
        }
        if let Some(val) = &order_direction {
            request = request.query(&[("order_direction", &val.to_string())]);
        }
        if let Some(opts) = &options {
            for (key, value) in &opts.additional_headers {
                request = request.header(key.as_str(), value.as_str());
            }
            for (key, value) in &opts.additional_query_params {
                request = request.query(&[(key.as_str(), value.as_str())]);
            }
            if let Some(timeout_seconds) = opts.timeout_seconds {
                request = request.timeout(std::time::Duration::from_secs(timeout_seconds));
            }
        }
        let config = self.config.get_dubbing_config();
        let config = match &options {
            Some(opts) if opts.token.is_some() || opts.api_key.is_some() => {
                let mut overridden = config.clone();
                if let Some(api_key) = &opts.api_key {
                    overridden.api_key = Some(api_key.clone());
                }
                overridden
            }
            _ => config,
        };
        for (key, value) in &config.custom_headers {
            request = request.header(key.as_str(), value.as_str());
        }
        request = crate::core::auth::apply_auth(&config, request, true);

        let response = self
            .http_client
            .send_with_retry(request, options.as_ref())
            .await?;

        if !response.status().is_success() {
            let status = response.status().as_u16();
            let body = response.text().await.unwrap_or_default();
            return Err(crate::error::ApiError::from_response(
                status,
                Some(body.as_str()),
            ));
        }

        let status = response.status().as_u16();
        let result: DubbingMetadataPageResponseModel =
            response
                .json()
                .await
                .map_err(|err| crate::error::ApiError::DecodeError {
                    status,
                    message: format!("{err}"),
                })?;
        Ok(result)
    }

