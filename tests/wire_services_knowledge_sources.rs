#[tokio::test]
async fn list_sends_the_real_wire_request() {
    let server = MockServer::start().await;
    let expected_response = serde_json::from_str::<serde_json::Value>(
        r#"[
        {
            "source_type": "file",
            "source_url": "value",
            "last_scraped_at_unix": 123,
            "original_filename": "value",
            "content_type": "value",
            "file_size_bytes": 123,
            "status": "processing",
            "error_message": "value",
            "failure_reason": "blocked_url",
            "crawl_entire_site": true,
            "scraped_pages_count": 123,
            "content_preview": "value",
            "processing_started_at_unix": 123,
            "id": "value",
            "created_at_unix": 123,
            "updated_at_unix": 123
        }
    ]"#,
    )
    .expect("fixture is valid JSON");

    Mock::given(method("GET"))
        .and(path("/v1/reception/knowledge-sources"))
        .respond_with(ResponseTemplate::new(200).set_body_json(expected_response.clone()))
        .expect(1)
        .mount(&server)
        .await;

    let config = ClientConfig::builder()
        .base_url(server.uri())
        .api_key("test_api_key")
        .build()
        .expect("config should build");
    let client = ApiClient::new(config).expect("client should construct");

    let result = client
        .knowledge_sources
        .list("value".to_string(), None)
        .await;
    assert!(result.is_ok(), "call failed: {:?}", result.as_ref().err());

    let received = server.received_requests().await.expect("requests recorded");
    let matched: Vec<_> = received
        .iter()
        .filter(|entry| {
            entry.method.as_str() == "GET" && entry.url.path() == "/v1/reception/knowledge-sources"
        })
        .collect();
    assert_eq!(
        matched.len(),
        1,
        "expected exactly one GET /v1/reception/knowledge-sources request"
    );
    let request = matched[0];
    assert_eq!(
        request
            .headers
            .get("xi-workspace-id")
            .map(|value| value.to_str().unwrap_or_default()),
        Some("value"),
        "header xi-workspace-id"
    );
    let auth_header = request
        .headers
        .get("xi-api-key")
        .map(|value| value.to_str().unwrap_or_default());
    assert!(
        auth_header.is_some_and(|value| value.starts_with("test_api_key")),
        "expected xi-api-key to start with \"test_api_key\", got {:?}",
        auth_header
    );
    let decoded = result.expect("call should succeed");
    assert_eq!(
        serde_json::to_value(&decoded).expect("response should serialize"),
        expected_response
    );
}

